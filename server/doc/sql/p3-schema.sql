 ('news_interval','3','首页资讯栏轮播间隔秒数'),
 ('news_empty_text','暂无资讯，敬请期待','无首页资讯时显示的文案');

CREATE TABLE IF NOT EXISTS home_channel (
 id BIGINT NOT NULL AUTO_INCREMENT, name VARCHAR(20) NOT NULL, sort_order INT NOT NULL DEFAULT 0,
 enabled BOOLEAN NOT NULL DEFAULT TRUE, create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
 update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP, PRIMARY KEY(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='首页频道Tab';
INSERT INTO home_channel(name,sort_order)
SELECT seed.name,seed.sort_order FROM (
 SELECT '观测枢' name,0 sort_order UNION ALL SELECT '发现',1 UNION ALL SELECT '官方',2 UNION ALL
 SELECT '酒馆',3 UNION ALL SELECT '攻略',4 UNION ALL SELECT '同人图',5 UNION ALL SELECT 'COS',6
) seed WHERE NOT EXISTS (SELECT 1 FROM home_channel);

CREATE TABLE IF NOT EXISTS home_entry (
 id BIGINT NOT NULL AUTO_INCREMENT, name VARCHAR(20) NOT NULL, icon_url VARCHAR(2048) NOT NULL DEFAULT '',
 link_url VARCHAR(2048) NOT NULL DEFAULT '', open_mode VARCHAR(10) NOT NULL DEFAULT 'inapp',
 show_topbar BOOLEAN NOT NULL DEFAULT TRUE, sort_order INT NOT NULL DEFAULT 0, enabled BOOLEAN NOT NULL DEFAULT TRUE,
 create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 PRIMARY KEY(id), CONSTRAINT chk_entry_mode CHECK(open_mode IN ('inapp','browser'))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='首页快捷入口';

CREATE TABLE IF NOT EXISTS notice_category (
 id BIGINT NOT NULL AUTO_INCREMENT, name VARCHAR(20) NOT NULL, icon_url VARCHAR(2048) NOT NULL DEFAULT '',
 sort_order INT NOT NULL DEFAULT 0, enabled BOOLEAN NOT NULL DEFAULT TRUE,
 create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 PRIMARY KEY(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='通知分类';
INSERT INTO notice_category(name,sort_order)
SELECT '系统通知',0 WHERE NOT EXISTS (SELECT 1 FROM notice_category);

CREATE TABLE IF NOT EXISTS notice (
 id BIGINT NOT NULL AUTO_INCREMENT, category_id BIGINT NOT NULL, title VARCHAR(100) NOT NULL,
 blocks TEXT NULL, post_id BIGINT NULL, status TINYINT NOT NULL DEFAULT 0, publish_time DATETIME NULL,
 create_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP, update_time DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
 PRIMARY KEY(id), KEY idx_notice_cat_status(category_id,status,publish_time DESC),
 CONSTRAINT fk_notice_cat FOREIGN KEY(category_id) REFERENCES notice_category(id),
 CONSTRAINT chk_notice_status CHECK(status IN (0,1))
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='通知内容';
