const fs = require('node:fs')
const path = require('node:path')
const assert = require('node:assert/strict')
const { chromium } = require('playwright-core')
const root = path.resolve(__dirname, '..')
const output = path.resolve(root, '../deliverables/reference-ui-20261018')
const base = process.env.UI_TEST_URL || 'http://127.0.0.1:15273/'
const near = (actual, expected, label) => assert(Math.abs(actual - expected) < 1, `${label}: ${actual} / ${expected}`)
;(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: process.env.UI_BROWSER_PATH || 'C:/Program Files/Google/Chrome/Application/chrome.exe' })
  const errors = [], results = []
  try {
    // Derive the native bitmap directly from the same vector used on Web.
    const icon = await browser.newPage({ viewport: { width: 96, height: 96 } })
    await icon.setContent('<body style="margin:0;background:transparent">' + fs.readFileSync(path.join(root, 'static/icons/top-cyan.svg'), 'utf8').replace('<svg ', '<svg width="96" height="96" '))
    await icon.locator('svg').screenshot({ path: path.join(root, 'static/native-raster/icons/top-cyan.png'), omitBackground: true })
    await icon.close()
    for (const width of [320, 390, 430]) {
      const context = await browser.newContext({ viewport: { width, height: Math.round(width * 2.2) }, isMobile: true, hasTouch: true })
      const page = await context.newPage()
      page.setDefaultTimeout(10000)
      page.on('pageerror', error => errors.push(error.message))
      await page.goto(base)
      await page.locator('.home-view .waterfall-post').first().waitFor()
      near((await page.locator('.feed-card').boundingBox()).y, width * 420 / 750, 'expanded header')
      const covers = page.locator('.waterfall-column .waterfall-cover')
      const first = await covers.first().boundingBox()
      near(first.x, width * 16 / 750, 'waterfall outer gutter')
      near(first.width, width * 351 / 750, 'waterfall column width')
      const tabs = await page.locator('.feed-card .channel-tabs').boundingBox()
      near(first.y - tabs.y - tabs.height, width * 18 / 750, 'waterfall top spacing')
      await page.screenshot({ path: path.join(output, `home-waterfall-${width}.png`) })
      // Scroll exactly to the seam, so the first card remains below the pinned tabs.
      const scroller = page.locator('.home-view .screen-scroll .uni-scroll-view .uni-scroll-view').first()
      await scroller.evaluate((element, top) => { element.scrollTop = top }, Math.ceil(width * (420 - 108) / 750))
      await page.locator('.home-compact').waitFor()
      const search = await page.locator('.home-compact .search-header').boundingBox()
      const channels = await page.locator('.home-compact .channel-tabs').boundingBox()
      near(search.height, width * 108 / 750, 'compact search height')
      near(search.y + search.height, channels.y, 'compact search/channel seam')
      await page.screenshot({ path: path.join(output, `home-waterfall-collapsed-${width}.png`) })
      await page.locator('.tab-bar .tab-item').first().click()
      await page.waitForFunction(() => getComputedStyle(document.querySelector('.home-compact')).visibility === 'hidden')
      // This browser context is isolated; the backend default and user device settings stay intact.
      await page.evaluate(() => uni.setStorageSync('settings_feed_layout', 'single'))
      await page.reload()
      await page.locator('.home-view .post-card').first().waitFor()
      const card = await page.locator('.home-view .post-card').first().boundingBox()
      const avatar = await page.locator('.home-view .author-avatar').first().boundingBox()
      near(card.width, width, 'single column width')
      near(avatar.x, width * 34 / 750, 'single column outer gutter')
      near(avatar.width, width * 54 / 750, 'single column avatar')
      await page.screenshot({ path: path.join(output, `home-single-${width}.png`) })
      const overflow = await page.evaluate(() => document.documentElement.scrollWidth > innerWidth)
      assert.equal(overflow, false, 'horizontal overflow')
      const bar = await page.locator('.tab-bar').boundingBox()
      near(bar.height, width * 128 / 750 + 1, 'bottom navigation height')
      results.push({ width, expanded: 'passed', collapsed: 'passed', waterfall: 'passed', single: 'passed', overflow: false })
      await context.close()
    }
    assert.deepEqual(errors, [])
    fs.writeFileSync(path.join(output, 'layout-verification.json'), JSON.stringify({ status: 'passed', scope: 'Real local data, isolated browser contexts; Android screenshots checked separately.', results, errors }, null, 2))
    console.log('Reference UI passed: 320/390/430px, expanded/collapsed headers, both feeds, gutters, navigation, no runtime errors.')
  } finally { await browser.close() }
})().catch(error => { console.error(error); process.exitCode = 1 })
