async function checkPane(page, pane, width, name) {
  const result = await page.locator(pane).evaluate(el => {
    const bounds = el.getBoundingClientRect()
    const cards = [...el.querySelectorAll('.post-card, .conversation')].map(card => {
      const rect = card.getBoundingClientRect()
      return { x: rect.x, width: rect.width }
    })
    const blocks = [...el.querySelectorAll('.skeleton-block, .media-fill')].map(block => getComputedStyle(block).backgroundColor)
    return { bounds: { x: bounds.x, width: bounds.width, height: bounds.height }, cards, blocks }
  })
  assert(Math.abs(result.bounds.width - width) <= 1, name + ': pane width')
  for (const card of result.cards) assert(card.x >= -1 && card.x + card.width <= width + 1, name + ': card overflow')
  for (const rgb of result.blocks) {
    const [r, g, b] = rgb.match(/\d+/g).map(Number)
    assert(r === g && g === b, name + ': non-gray skeleton')
  }
  const bottom = await page.locator('.tab-bar').boundingBox()
  assert(Math.abs(result.bounds.height - bottom.y) < 1, name + ': content must end above bottom navigation')
  const pageWidth = await page.evaluate(() => document.documentElement.scrollWidth)
  assert.equal(pageWidth, width, name + ': document horizontal overflow')
}
async function destination(page, trigger, expectedKind) {
  await trigger.click()
  if (expectedKind === 'search') {
    await page.waitForSelector('.ct-search-page')
    assert(page.url().includes('/pages/search/index'), 'wrong search destination: ' + page.url())
    await page.locator('.ct-search-cancel').click()
    await page.waitForSelector('.app-shell')
    await sleep(140)
    return
  }
  if (expectedKind === 'settings') {
    await page.waitForSelector('.settings-page')
    assert(page.url().includes('/pages/settings/index'), 'wrong settings destination: ' + page.url())
    await screenshot(page, 'settings-390')
    await page.locator('.settings-page [aria-label="返回"]').click()
    await page.waitForSelector('.app-shell')
    await sleep(140)
    return
  }
  if (expectedKind === 'post') {
    await page.waitForSelector('.post-detail')
    assert(page.url().includes('/pages/post/index?id='), 'wrong post destination: ' + page.url())
    await page.locator('.post-detail [aria-label="返回"]').click()
    await page.waitForSelector('.app-shell')
    await sleep(140)
    return
  }
  await page.waitForSelector('.destination-page')
  assert(page.url().includes('kind=' + expectedKind), 'wrong destination: ' + page.url())
  assert.equal(await page.locator('.destination-header').count(), 1)
  await page.locator('.destination-header [aria-label="返回"]').click()
  await page.waitForSelector('.app-shell')
  await sleep(140)
}
